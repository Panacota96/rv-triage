//! Golden vectors of every date/time text the collection writes, frozen from chrono 0.4.45 before the move off
//! chrono (RUSTSEC-2026-0543): file-system times (100-ns, `YYYY-MM-DDTHH:MM:SS.fffffffZ`) from the file API and
//! from raw NTFS, FILETIME values of the live capture, and the host clock facts. Every text must stay
//! byte-identical. Regenerate (only on purpose):
//! `cargo test -p rv-triage-core golden_time::print -- --ignored --nocapture`.

use super::ntfs_source::volume::nt_time;
use super::source::utc;
use std::time::{Duration, SystemTime, UNIX_EPOCH};

/// 100-ns intervals between 1601-01-01 and 1970-01-01.
const DIFF: u64 = 116_444_736_000_000_000;

fn instants() -> Vec<SystemTime> {
    vec![
        UNIX_EPOCH,
        UNIX_EPOCH + Duration::new(1_763_200_000, 123_456_789),
        UNIX_EPOCH + Duration::new(1_763_200_000, 999_999_999),
        UNIX_EPOCH + Duration::new(1_763_200_000, 50),
        UNIX_EPOCH + Duration::new(1_767_323_045, 999_999_900),
        UNIX_EPOCH - Duration::from_millis(1500),
        UNIX_EPOCH - Duration::new(0, 100),
        UNIX_EPOCH - Duration::new(1_000_000_000, 250_000_000),
        UNIX_EPOCH - Duration::new(11_644_473_600, 0),
        UNIX_EPOCH + Duration::new(2_147_483_648, 1_000_000),
        UNIX_EPOCH + Duration::new(253_402_300_799, 999_999_900),
        UNIX_EPOCH + Duration::new(253_402_300_800, 0),
        UNIX_EPOCH + Duration::new(910_692_730_085, 477_580_700),
    ]
}

fn nt_values() -> Vec<u64> {
    vec![
        0,
        1,
        9_999_999,
        10_000_000,
        DIFF - 1,
        DIFF,
        DIFF + 1,
        DIFF + 17_632_000_001_234_567,
        (1_767_323_045 + 11_644_473_600) * 10_000_000 + 9_999_999,
        (253_402_300_799 + 11_644_473_600) * 10_000_000 + 9_999_999,
        (253_402_300_800 + 11_644_473_600) * 10_000_000,
        i64::MAX as u64,
        i64::MAX as u64 + 1,
        u64::MAX,
    ]
}

fn lines() -> Vec<String> {
    let mut v = vec![];
    for (i, t) in instants().into_iter().enumerate() {
        v.push(format!("instant {i} -> {:?}", utc(Ok(t))));
    }
    v.push(format!(
        "err -> {:?}",
        utc(Err(std::io::Error::other("no time")))
    ));
    for n in nt_values() {
        v.push(format!("nt {n} -> {:?}", nt_time(ntfs::NtfsTime::from(n))));
    }
    #[cfg(windows)]
    {
        use super::host::windows_impl::{clock_texts, filetime_utc};
        for n in nt_values() {
            let n = n as i64;
            v.push(format!("filetime {n} -> {:?}", filetime_utc(n)));
        }
        for n in [-1i64, i64::MIN] {
            v.push(format!("filetime {n} -> {:?}", filetime_utc(n)));
        }
        let ups = [
            0u64,
            1,
            1_500,
            86_400_000,
            9_223_372_036_854_775,
            i64::MAX as u64,
            i64::MAX as u64 + 1,
            u64::MAX,
        ];
        let biases = [
            0, -60, 300, -330, -345, 720, -840, 1439, -1439, 1440, -1440, 100_000,
        ];
        for (k, t) in instants().into_iter().enumerate() {
            for (i, up) in ups.iter().enumerate() {
                let bias = biases[i % biases.len()];
                v.push(format!(
                    "clock {k} {up} {bias} -> {:?}",
                    clock_texts(t, *up, bias)
                ));
            }
            for bias in biases {
                v.push(format!(
                    "clock {k} 0 {bias} -> {:?}",
                    clock_texts(t, 0, bias).1
                ));
            }
        }
    }
    v
}

#[test]
fn golden_time_texts() {
    let got = lines();
    let want: &[&str] = if cfg!(windows) {
        WANT
    } else {
        &WANT[..WANT_PORTABLE]
    };
    assert_eq!(got.len(), want.len());
    for (g, w) in got.iter().zip(want) {
        assert_eq!(g, w);
    }
}

